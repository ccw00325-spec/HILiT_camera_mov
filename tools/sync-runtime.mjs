// 비공개 제품 정본의 커밋에서 runtime/ 을 다시 뽑는다. 사본을 직접 고치지 않는다. 범위는 tools/public-scope.json.
//   HILIT_WEB_REPO=<웹 정본> HILIT_ANDROID_REPO=<Android 정본> node tools/sync-runtime.mjs [--check]
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isStampable, fileFingerprint, MARK, PROJECT, REPO_URL, stampSource } from './lib/stamp.mjs';
import { K, WINDOW, winnow } from './lib/winnow.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const RUNTIME = path.join(ROOT, 'runtime');
const check = process.argv.includes('--check');
const SCRUB = JSON.parse(process.env.HILIT_SYNC_SCRUB ?? '[]');
const scope = JSON.parse(readFileSync(path.join(ROOT, 'tools/public-scope.json'), 'utf8'));
const repos = [{ env: 'HILIT_WEB_REPO', paths: scope.web }, { env: 'HILIT_ANDROID_REPO', paths: scope.android }];
for (const repo of repos) {
  repo.dir = process.env[repo.env];
  if (!repo.dir || !existsSync(path.join(repo.dir, '.git'))) { console.error(repo.env + ' 에 정본 폴더를 지정해 주세요.'); process.exit(2); }
  repo.git = (...a) => execFileSync('git', ['-C', repo.dir, '-c', 'core.quotepath=false', ...a], { maxBuffer: 1 << 29 });
  repo.git('fetch', 'origin', '--quiet');
  repo.commit = repo.git('rev-parse', 'origin/main').toString().trim();
}

function transform(rel, text) {
  let out = text
    .replace(/\/\*(?:(?!\*\/)[\s\S])*?HILiT-OWN-2026(?:(?!\*\/)[\s\S])*?\*\/[ \t]*\r?\n?/g, '')
    .replace(/^[ \t]*\*[ \t]*특허 조사는 하지 않았다\.[ \t]*\r?\n/m, '')
    .replace('"license": "UNLICENSED"', '"license": "SEE LICENSE IN LICENSE"');
  for (const [from, to] of SCRUB) out = out.replaceAll(from, to);
  return out;
}

const output = new Map();
for (const repo of repos) {
  const listed = repo.git('ls-tree', '-r', 'origin/main', '--name-only', '--', ...repo.paths).toString().split('\n').filter(Boolean);
  for (const rel of listed) {
    if (/\.(onnx|tflite|task|pth|pt|ckpt|bin|safetensors|wasm|apk|aab|mp4|mov|png|jpe?g|webp)$/i.test(rel) || /package-lock\.json$/.test(rel)) continue;
    const text = transform(rel, repo.git('show', 'origin/main:' + rel).toString('utf8'));
    output.set('runtime/' + rel, isStampable(rel) ? stampSource('runtime/' + rel, text) : text);
  }
}
const entries = [...output].filter(([p]) => /\.(ts|tsx|js|mjs|java)$/.test(p));
const count = new Map();
const hashes = new Map();
for (const [p, text] of entries) { const h = winnow(text); hashes.set(p, h); for (const v of h) count.set(v, (count.get(v) ?? 0) + 1); }
const files = entries.map(([p]) => ({ p, h: hashes.get(p).filter((v) => count.get(v) < 4) })).filter((f) => f.h.length >= 8)
  .map((f) => ({ p: f.p, fp: fileFingerprint(f.p), h: f.h.map((v) => v.toString(36)).join(' ') }));
output.set('fingerprints/index.json', JSON.stringify({ schema: 'hilit-code-fingerprints-v1', project: PROJECT, url: REPO_URL, mark: MARK, k: K, w: WINDOW, files }) + '\n');
output.set('runtime/SOURCE.json', JSON.stringify({ note: 'Generated by tools/sync-runtime.mjs from private product commits. Do not edit runtime/ by hand.', web: repos[0].commit, android: repos[1].commit }, null, 2) + '\n');

const walk = (d, b) => (existsSync(d) ? readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name), b + '/' + e.name) : [b + '/' + e.name])) : []);
if (check) {
  const diffs = [];
  for (const [p, text] of output) { const f = path.join(ROOT, p); if (!existsSync(f) || readFileSync(f, 'utf8') !== text) diffs.push('다름 ' + p); }
  for (const p of walk(RUNTIME, 'runtime')) if (!output.has(p)) diffs.push('남는 파일 ' + p);
  if (diffs.length) { console.error(diffs.slice(0, 20).join('\n')); process.exit(1); }
  console.log('사본 일치: ' + output.size + '개');
} else {
  rmSync(RUNTIME, { recursive: true, force: true });
  for (const [p, text] of output) { const f = path.join(ROOT, p); mkdirSync(path.dirname(f), { recursive: true }); writeFileSync(f, text); }
  console.log('사본 갱신: ' + output.size + '개, 코드 지문 ' + files.length + '개 (web ' + repos[0].commit.slice(0, 8) + ' · android ' + repos[1].commit.slice(0, 8) + ')');
}
